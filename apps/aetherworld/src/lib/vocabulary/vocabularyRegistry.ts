/* ============ 索引与查询工具 ============ */

export function getAllTerms(): VocabularyTerm[] {
  return VOCABULARY_REGISTRY;
}
export function getTermById(id: string): VocabularyTerm | undefined {
  return VOCABULARY_REGISTRY.find((t) => t.termId === id);
}
export function getTermsByCategory(cat: TermCategoryId): VocabularyTerm[] {
  return VOCABULARY_REGISTRY.filter((t) => t.category === cat);
}
export function getTermsBySystemLayer(layer: TermSystemLayerId): VocabularyTerm[] {
  return VOCABULARY_REGISTRY.filter((t) => t.systemLayer === layer);
}
export function getTermsByAudience(mode: TermAudienceMode): VocabularyTerm[] {
  return VOCABULARY_REGISTRY.filter((t) =>
    mode === "FOUNDER" ? true : (mode === "ADVANCED" ? t.audienceMode !== "FOUNDER" : t.audienceMode === "PUBLIC"),
  );
}
export function searchTerms(keyword: string, audience: TermAudienceMode = "PUBLIC"): VocabularyTerm[] {
  const k = keyword.trim().toLowerCase();
  if (!k) return [];
  const pool = getTermsByAudience(audience);
  return pool.filter((t) => {
    const hay = [
      t.termId, t.chineseTerm, t.englishTerm,
      ...(t.aliases ?? []),
      t.shortDefinition, t.plainDefinition, t.technicalDefinition,
    ].join(" ").toLowerCase();
    return hay.includes(k);
  });
}
export function getCoreCounts() {
  return {
    totalTerms: VOCABULARY_REGISTRY.length,
    activeTerms: VOCABULARY_REGISTRY.filter((t) => t.maturity === "ACTIVE").length,
    founderLockedTerms: VOCABULARY_REGISTRY.filter((t) => t.founderLocked).length,
    deprecatedTerms: VOCABULARY_REGISTRY.filter((t) => t.maturity === "DEPRECATED").length,
  };
}
