/** 快速构造工具，减少冗余。 */
function t(
  termId: string,
  chineseTerm: string,
  englishTerm: string,
  category: TermCategoryId,
  systemLayer: TermSystemLayerId,
  shortDefinition: string,
  plainDefinition: string,
  technicalDefinition: string,
  opts: Partial<VocabularyTerm> = {},
): VocabularyTerm {
  return {
    termId,
    chineseTerm,
    englishTerm,
    aliases: opts.aliases ?? [],
    category,
    systemLayer,
    maturity: opts.maturity ?? "ACTIVE",
    audienceMode: opts.audienceMode ?? "PUBLIC",
    shortDefinition,
    plainDefinition,
    technicalDefinition,
    sourceType: opts.sourceType ?? "SYSTEM",
    relatedModules:  opts.relatedModules  ?? [],
    relatedEngines:  opts.relatedEngines  ?? [],
    relatedCalculus: opts.relatedCalculus ?? [],
    relatedTerms:    opts.relatedTerms    ?? [],
    correctUsage:    opts.correctUsage,
    commonMisuse:    opts.commonMisuse    ?? [],
    safetyBoundary:  opts.safetyBoundary  ?? "属于 Aetherworld 产品内部概念，不代表现实事实、现实金融资产或绝对预测。",
    exampleUsages:   opts.exampleUsages,
    localization:    opts.localization    ?? [{ locale: "en", displayTerm: englishTerm }],
    version:         opts.version         ?? V,
    founderLocked:   opts.founderLocked   ?? false,
    createdAt:       NOW,
    updatedAt:       NOW,
  };
}

