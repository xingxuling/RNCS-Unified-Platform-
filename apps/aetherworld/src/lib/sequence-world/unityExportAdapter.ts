// Unity Export Adapter — camelCase JSON + C# skeleton
import type { SequenceWorldExport } from "./engineExportAdapter";

export function exportUnityJSON(world: SequenceWorldExport): string {
  // already camelCase; just stringify
  return JSON.stringify(world, null, 2);
}

export function exportUnityCSharpSkeleton(world: SequenceWorldExport): string {
  return [
    `// Auto-generated by Aether Sequence World Engine v${world.metadata.engineVersion}`,
    `// Source mode: ${world.metadata.sourceMode}`,
    `using System;`,
    `using System.Collections.Generic;`,
    `using UnityEngine;`,
    ``,
    `[Serializable] public class SequenceWorldMetadata {`,
    `    public string engineVersion;`,
    `    public string generatedAt;`,
    `    public string sourceMode;`,
    `    public string targetType;`,
    `}`,
    ``,
    `[Serializable] public class WorldStateProfile {`,
    `    public string worldName;`,
    `    public string worldMood;`,
    `    public string dominantForce;`,
    `    public string currentPhase;`,
    `    public float entropyLevel;`,
    `    public float eventPressure;`,
    `    public float stability;`,
    `    public string worldDescription;`,
    `}`,
    ``,
    `[Serializable] public class RenderProfile {`,
    `    public string paletteName;`,
    `    public string[] primaryColors;`,
    `    public string[] accentColors;`,
    `    public string backgroundStyle;`,
    `    public string lightingStyle;`,
    `    public string[] materialStyle;`,
    `    public float particleDensity;`,
    `    public string[] symbolMotifs;`,
    `    public string cameraMood;`,
    `    public string uiDensity;`,
    `    public string[] visualKeywords;`,
    `}`,
    ``,
    `[Serializable] public class SequenceWorldExport {`,
    `    public SequenceWorldMetadata metadata;`,
    `    public WorldStateProfile worldState;`,
    `    public RenderProfile renderProfile;`,
    `    // NOTE: physics / animation / npc / quests / zones omitted in skeleton.`,
    `    // Use full JSON via JsonUtility or Newtonsoft.Json for richer mapping.`,
    `}`,
    ``,
    `public class SequenceWorldLoader : MonoBehaviour {`,
    `    public TextAsset profileJson;`,
    `    void Awake() {`,
    `        if (profileJson == null) { Debug.LogWarning("Missing sequence world profile"); return; }`,
    `        var data = JsonUtility.FromJson<SequenceWorldExport>(profileJson.text);`,
    `        Debug.Log($"[Aether] Loaded world {data.worldState.worldName} phase={data.worldState.currentPhase}");`,
    `        // TODO: apply renderProfile to materials/lights, instantiate NPCs, spawn zones`,
    `    }`,
    `}`,
    ``,
    `// NOTE: This skeleton does NOT replace Unity's renderer, physics, or animation systems.`,
    `// It is a logic + presentation layer SDK. Aether SDK provides profiles; Unity executes.`,
  ].join("\n");
}
